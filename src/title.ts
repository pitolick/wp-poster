/**
 * Google 検索結果でのタイトル切り落とし対策。
 *
 * Google はタイトルを書き換える際、半角の区切り文字（`:` `/` `|`）を「セクション区切り」
 * とみなして片側を丸ごと落とすことがある。例えば「オーメン:ザ・ファースト」を半角コロンで
 * 書くと、検索結果に「オーメン」とだけ表示され別作品と誤認される。全角（`：` `／` `｜`）は
 * 区切りと認識されにくいため、この関数は「区切りとして使われた半角記号」だけを全角へ畳む。
 *
 * 変換するのは、半角 `:` `/` `|` のうち **次のいずれか** に該当するもの:
 *   (a) 直前が CJK 文字（漢字・かな・カナ・長音符）＝日本語タイトル内の区切り
 *   (b) 前後どちらかに空白がある＝言語を問わず区切り用途
 * いずれの場合も隣接空白は畳む（全角約物は前後に空白を取らない慣習に合わせる）。
 *
 * 空白を伴わず Latin 直後に現れる記号（`Dr.STONE` の `.`、`Re:ゼロ` の `:`）は公式表記と
 * みなして変更しない。冪等（全角化後は対象の半角記号が無く、再適用しても変わらない）。
 */
export function normalizeTitleSeparators(title: string): string {
  const FULLWIDTH: Record<string, string> = { ':': '：', '/': '／', '|': '｜' };

  return (
    title
      // (b) 前後どちらかに空白がある半角区切り → 全角化して隣接空白を畳む。
      //     `\s+X\s*`（前に空白）または `\s*X\s+`（後に空白）にマッチさせ、
      //     少なくとも片側の空白を必須にする。
      .replace(/\s+([:/|])\s*|\s*([:/|])\s+/g, (_m, a?: string, b?: string) => FULLWIDTH[a ?? b!])
      // (a) 直前が CJK の半角区切り（空白なし） → 全角化。
      //     (b) で全角化済みの箇所は対象記号が残らないため二重変換されない。
      .replace(/(?<=[぀-ヿ㐀-䶿一-鿿豈-﫿])([:/|])/g, (_m, s: string) => FULLWIDTH[s])
  );
}
